// Команда staticlint выполняет статический анализ кода.
//
// Multichecker включает следующие анализаторы:
//
// Стандартные анализаторы Go:
//   - assign — обнаруживает бесполезные присваивания.
//   - atomic — проверяет корректность использования атомарных операций.
//   - bools — обнаруживает ошибки в логических выражениях.
//   - copylocks — выявляет копирование значений, содержащих блокировки.
//   - printf — проверяет форматирование строк.
//   - shadow — обнаруживает затенение переменных.
//
// Staticcheck:
//   - SA — все анализаторы класса, проверяющие корректность кода.
//   - ST1005 — проверяет формат сообщений об ошибках.
//
// Сторонние анализаторы:
//   - nilerr — обнаруживает возврат nil вместо возникшей ошибки.
//   - bodyclose — проверяет закрытие тела HTTP-ответа.
//
// Собственный анализатор:
//   - noexit — запрещает прямой вызов os.Exit в функции main пакета main.
//
// # Запуск
//
//	go run ./cmd/staticlint ./...
//
// # Запуск с исключением сгенерированных моков
//
//	go list ./... | grep -v '/mocks$' | xargs go run ./cmd/staticlint

