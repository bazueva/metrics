package main

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/types"
	"log"
	"os"
	"path/filepath"
	"strings"
	"text/template"

	"golang.org/x/tools/go/packages"
)

const templateReset = `
func (m *{{.Spec.Name}}) Reset() {
    if m == nil {
        return
    }
{{- range fields .Spec}}
{{- $field := .}}
{{- range fieldNames .}}
{{- $code := resetField . $field.Type $.Info}}
{{- if $code}}
    {{$code}}
{{- end}}
{{- end}}
{{- end}}
}
`

var resetTemplate = template.Must(
	template.New("reset").
		Funcs(template.FuncMap{
			"fields":     fields,
			"fieldNames": fieldNames,
			"resetField": resetField,
		}).
		Parse(templateReset),
)

type resetTemplateData struct {
	Spec *ast.TypeSpec
	Info *types.Info
}

func main() {
	cfg := &packages.Config{
		Mode: packages.NeedName |
			packages.NeedFiles |
			packages.NeedSyntax |
			packages.NeedTypes |
			packages.NeedTypesInfo,
	}

	pkgs, err := packages.Load(cfg, "./...")
	if err != nil {
		log.Fatal(err)
	}

	for _, pkg := range pkgs {
		if filepath.Base(pkg.PkgPath) == "mocks" {
			continue
		}

		if len(pkg.GoFiles) == 0 {
			continue
		}

		var buf bytes.Buffer

		fmt.Fprintf(
			&buf,
			"// Code generated by reset; DO NOT EDIT.\n\npackage %s\n\n",
			pkg.Name,
		)

		found := false

		for _, file := range pkg.Syntax {
			ast.Inspect(file, func(node ast.Node) bool {
				decl, ok := node.(*ast.GenDecl)
				if !ok {
					return true
				}

				for _, spec := range decl.Specs {
					typeSpec, ok := spec.(*ast.TypeSpec)
					if !ok {
						continue
					}

					if _, ok := typeSpec.Type.(*ast.StructType); !ok {
						continue
					}

					doc := typeSpec.Doc
					if doc == nil {
						doc = decl.Doc
					}
					if doc == nil {
						continue
					}

					hasDirective := false
					for _, comment := range doc.List {
						if strings.TrimSpace(strings.TrimPrefix(comment.Text, "//")) == "generate:reset" {
							hasDirective = true
							break
						}
					}

					if !hasDirective {
						continue
					}

					if err := generateReset(typeSpec, pkg.TypesInfo, &buf); err != nil {
						log.Fatal(err)
					}

					found = true
				}

				return true
			})
		}

		if !found {
			continue
		}

		formatted, err := format.Source(buf.Bytes())
		if err != nil {
			log.Fatal(err)
		}

		filename := filepath.Join(filepath.Dir(pkg.GoFiles[0]), "reset.gen.go")

		if err := os.WriteFile(filename, formatted, 0644); err != nil {
			log.Fatal(err)
		}
	}
}

func generateReset(spec *ast.TypeSpec, info *types.Info, buf *bytes.Buffer) error {
	return resetTemplate.Execute(buf, resetTemplateData{
		Spec: spec,
		Info: info,
	})
}

func fields(spec *ast.TypeSpec) []*ast.Field {
	structType, ok := spec.Type.(*ast.StructType)
	if !ok {
		return nil
	}

	return structType.Fields.List
}

func fieldNames(field *ast.Field) []string {
	names := make([]string, 0, len(field.Names))

	for _, name := range field.Names {
		names = append(names, name.Name)
	}

	return names
}

func hasResetMethod(expr ast.Expr, info *types.Info) bool {
	t := info.TypeOf(expr)
	if t == nil {
		return false
	}

	if ptr, ok := t.(*types.Pointer); ok {
		t = ptr.Elem()
	}

	if _, ok := t.Underlying().(*types.Struct); !ok {
		return false
	}

	methodSet := types.NewMethodSet(types.NewPointer(t))
	selection := methodSet.Lookup(nil, "Reset")
	if selection == nil {
		return false
	}

	signature, ok := selection.Obj().Type().(*types.Signature)
	if !ok {
		return false
	}

	return signature.Params().Len() == 0 &&
		signature.Results().Len() == 0
}

func resetField(name string, expr ast.Expr, info *types.Info) string {
	target := "m." + name

	t := info.TypeOf(expr)
	if t == nil {
		return ""
	}

	// Интерфейсы обрабатываем отдельно.
	if _, ok := t.Underlying().(*types.Interface); ok {
		return fmt.Sprintf(`
if resetter, ok := %s.(interface{ Reset() }); ok && resetter != nil {
	resetter.Reset()
}`, target)
	}

	// Вложенные структуры с методом Reset().
	if hasResetMethod(expr, info) {
		if _, ok := t.(*types.Pointer); ok {
			return fmt.Sprintf(`
if %s != nil {
	%s.Reset()
}`, target, target)
		}

		return target + ".Reset()"
	}

	// Указатели на примитивы, срезы и мапы.
	if ptr, ok := expr.(*ast.StarExpr); ok {
		code := resetValue("(*"+target+")", ptr.X)
		if code == "" {
			return ""
		}

		return fmt.Sprintf("if %s != nil {\n%s\n}", target, code)
	}

	return resetValue(target, expr)
}

func resetValue(target string, expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		switch t.Name {
		case "string":
			return target + ` = ""`
		case "bool":
			return target + " = false"
		case "int", "int8", "int16", "int32", "int64",
			"uint", "uint8", "uint16", "uint32", "uint64", "uintptr",
			"float32", "float64":
			return target + " = 0"
		}

	case *ast.ArrayType:
		if t.Len == nil {
			return fmt.Sprintf("%s = %s[:0]", target, target)
		}

	case *ast.MapType:
		return fmt.Sprintf("clear(%s)", target)
	}

	return ""
}
